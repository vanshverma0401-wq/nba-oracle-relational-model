from __future__ import annotations

import re
import unittest
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


class OraclePackageTests(unittest.TestCase):
    def test_required_files_exist(self) -> None:
        required = {
            ROOT / "README.md",
            ROOT / "schema.sql",
            ROOT / "sample_data.sql",
            ROOT / "analysis_queries.sql",
            ROOT / "METHODS_AND_LIMITATIONS.md",
            ROOT / "DATA_AND_USAGE.md",
            ROOT / "LICENSE",
        }
        self.assertFalse([path.relative_to(ROOT) for path in required if not path.is_file()])

    def test_schema_contains_five_tables_and_integrity_controls(self) -> None:
        schema = (ROOT / "schema.sql").read_text(encoding="utf-8").lower()
        tables = {"teams", "positions", "players", "games", "player_stats"}
        self.assertEqual(len(re.findall(r"\bcreate\s+table\b", schema)), 5)
        for table in tables:
            self.assertRegex(schema, rf"\bcreate\s+table\s+{table}\b")
        for contract in ("primary key", "foreign key", "check", "unique"):
            self.assertIn(contract, schema)
        self.assertGreaterEqual(len(re.findall(r"\bcreate\s+index\b", schema)), 5)
        self.assertNotIn("insert into", schema)

    def test_analysis_includes_joins_aggregation_and_reusable_view(self) -> None:
        queries = (ROOT / "analysis_queries.sql").read_text(encoding="utf-8").lower()
        self.assertIn("create or replace view player_team_summary", queries)
        self.assertGreaterEqual(len(re.findall(r"\bjoin\b", queries)), 6)
        self.assertIn("group by", queries)
        self.assertIn("sum(", queries)
        self.assertIn("row_number() over", queries)

    def test_sample_data_is_fictional_and_not_source_dataset_reuse(self) -> None:
        sample = (ROOT / "sample_data.sql").read_text(encoding="utf-8")
        self.assertIn("fictional demonstration data", sample.lower())
        banned = {
            "Lakers",
            "Warriors",
            "LeBron James",
            "Stephen Curry",
            "Jayson Tatum",
            "Basketball Reference",
        }
        self.assertFalse([name for name in banned if name.lower() in sample.lower()])
        self.assertGreaterEqual(len(re.findall(r"(?i)\binsert\s+into\b", sample)), 20)

    def test_documentation_keeps_execution_and_trigger_claims_bounded(self) -> None:
        readme = (ROOT / "README.md").read_text(encoding="utf-8")
        required = {
            "five-table Oracle relational model",
            "fictional sample data",
            "static package checks",
            "execution in Oracle remains `Needs Evidence`",
            "recovered final DDL contains executable trigger source",
        }
        self.assertTrue(all(statement in readme for statement in required))

    def test_no_private_or_personal_patterns(self) -> None:
        patterns = {
            "private_path": re.compile(r"/(?:Users|Volumes|home)/[^\s`]+"),
            "email": re.compile(r"\b[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}\b", re.I),
            "ip_address": re.compile(r"\b(?:\d{1,3}\.){3}\d{1,3}\b"),
            "course_platform": re.compile(r"(?i)canvas|instructure|grade|instructor solution"),
        }
        findings: list[str] = []
        for path in ROOT.rglob("*"):
            if ".git" in path.relative_to(ROOT).parts:
                continue
            if not path.is_file() or path.name == "test_sql_package.py" or path.suffix == ".pyc":
                continue
            content = path.read_text(encoding="utf-8", errors="ignore")
            # The generated DDL tool version resembles an address; it is not one.
            if path == ROOT / "coursework" / "final_schema.sql":
                content = "\n".join(line for line in content.splitlines()
                                    if not line.startswith("-- Generated by Oracle SQL Developer Data Modeler"))
            for label, pattern in patterns.items():
                if pattern.search(content):
                    findings.append(f"{path.relative_to(ROOT)}: {label}")
        self.assertFalse(findings, findings)

    def test_original_final_source_has_expected_objects(self) -> None:
        source = (ROOT / "coursework" / "final_schema.sql").read_text().lower()
        self.assertEqual(len(re.findall(r"\bcreate\s+table\b", source)), 8)
        self.assertEqual(len(re.findall(r"\bcreate\s+view\b", source)), 3)
        self.assertEqual(len(re.findall(r"\bforeign\s+key\b", source)), 10)
        self.assertIn("create or replace trigger track_win_loss_updates", source)
        self.assertIn("team_stats_log_seq.nextval", source)

    def test_markdown_links_resolve(self) -> None:
        missing: list[str] = []
        for markdown in ROOT.rglob("*.md"):
            content = markdown.read_text(encoding="utf-8")
            for target in re.findall(r"!?\[[^\]]*\]\(([^)]+)\)", content):
                if re.match(r"^[a-z]+://", target, re.I) or target.startswith("#"):
                    continue
                if not (markdown.parent / target.split("#", 1)[0]).is_file():
                    missing.append(f"{markdown.relative_to(ROOT)} -> {target}")
        self.assertFalse(missing, missing)


if __name__ == "__main__":
    unittest.main()
